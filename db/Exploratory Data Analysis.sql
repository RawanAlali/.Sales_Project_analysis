--Dimensions Exploration
select count(customer_id) from customers
select count(distinct customer_id) from customers
select count(country) from customers
select count(distinct country) from customers
-- Retrieve a list of unique countries from which customers originate

select distinct country from customers

select count(category) from products
select count(distinct category) from products
select distinct category from products
-- Retrieve a list of unique categories, subcategories, and products
select distinct category,
subcategory,
product_name
from products
order by category,
subcategory,
product_name

--Date Range Exploration 
-- Determine the first and last order date and the total duration in months

select min(order_date) first_order,
max(order_date) last_order,
concat(DATEDIFF(year,min(order_date),max(order_date)),' year') order_range_year,
concat(DATEDIFF(month,min(order_date),max(order_date)),' month') order_range_month
from fact_sales

-- Find the youngest and oldest customer based on birthdate

select 
min(birthdate) oldest_customer,
concat(datediff(year,min(birthdate),getdate()),' year') oldest_age,
max (birthdate) youngest_customer  ,
concat(datediff(year,max(birthdate),getdate()),' year') youngest_age,
concat(datediff(year,min(birthdate),max (birthdate)),' year') differnce
from customers

--Measures Exploration 


-- Find the Total Sales
SELECT 
SUM(sales_amount) AS total_sales 
FROM fact_sales

-- Find how many items are sold
SELECT SUM(quantity) AS total_quantity FROM fact_sales

-- Find the average selling price
SELECT AVG(price) AS avg_price FROM  fact_sales

-- Find the Total number of Orders
SELECT COUNT(order_number) AS total_orders FROM fact_sales
SELECT COUNT(DISTINCT order_number) AS total_orders FROM fact_sales

-- Find the total number of products
SELECT COUNT(product_name) AS total_products FROM products

-- Find the total number of customers
SELECT COUNT(customer_key) AS total_customers FROM customers;
SELECT COUNT(distinct customer_key) AS total_customers FROM customers;

-- Find the total number of customers that has placed an order
SELECT COUNT(DISTINCT customer_key) AS total_customers FROM fact_sales;

-- Generate a Report that shows all key metrics of the business

SELECT 
'total_sales' as measure_name ,SUM(sales_amount) as measure_value FROM fact_sales
union
SELECT 'total_quantity' , SUM(quantity) FROM fact_sales
union
SELECT ' avg_price', AVG(price)  FROM  fact_sales
union
SELECT ' total_orders' ,COUNT(order_number)  FROM fact_sales
union
SELECT ' total_customers' ,COUNT(customer_key) FROM customers;

--Magnitude Analysis

-- Find total customers by countries

select country,
count(customer_id) customer_number
 from customers
group by country 
order by count(customer_id) desc

-- Find total customers by gender

select gender,
count(customer_id) customer_number
 from customers
group by gender 
order by count(customer_id)

-- Find total products by category

select category,
count(product_key) Product_number
 from products
group by category 
order by count(product_key) 

-- What is the average costs in each category?

select category,
avg(cost) avg_cost
from products
group by category 
order by avg(cost) desc

-- What is the total revenue generated for each category?

select
p.category,
sum(sales_amount) sum_sale 
from fact_sales f
left join products p
on f.product_key=p.product_key
group by p.category
order by sum(sales_amount) desc

-- What is the total revenue generated by each customer?

select f.customer_key,
concat(c.first_name,' ',c.last_name)as customer_name,
sum(sales_amount) total_sale
from fact_sales f
left join customers c
on f.customer_key=c.customer_key
group by  f.customer_key,
concat(c.first_name,' ',c.last_name)
order by sum(sales_amount) desc

-- What is the distribution of sold items across countries?

select country,
count(f.order_number) as total_order,
sum(quantity) as sold_items 
from fact_sales f
left join customers c
on f.customer_key=c.customer_key
group by country
order by sold_items desc

--Ranking Analysis



-- Which 5 products Generating the Highest Revenue?

select  top 5 product_name,
sum(f.sales_amount) as  total_sale
from fact_sales f
left join products p
on f.product_key=p.product_key
group by product_name
order by total_sale desc

--or we can
select * from(
select  product_name,
sum(f.sales_amount) as  total_sale,
ROW_NUMBER()over(order by sum(f.sales_amount) desc) rank_products
from fact_sales f
left join products p
on f.product_key=p.product_key
group by product_name) as ranked_products
where rank_products<=5

-- What are the 5 worst-performing products in terms of sales?
select * from(
select  product_name,
sum(f.sales_amount) as  total_sale,
ROW_NUMBER()over(order by sum(f.sales_amount) ) rank_products
from fact_sales f
left join products p
on f.product_key=p.product_key
group by product_name) as ranked_products
where rank_products<=5

-- Find the top 10 customers who have generated the highest revenue

select top 10 f.customer_key,
concat(c.first_name,' ',c.last_name)as customer_name,
sum(sales_amount) total_sale
from fact_sales f
left join customers c
on f.customer_key=c.customer_key
group by  f.customer_key,
concat(c.first_name,' ',c.last_name)
order by sum(sales_amount) desc

select * from(
select f.customer_key,
concat(c.first_name,' ',c.last_name)as customer_name,
sum(sales_amount) total_sale,
rank()over(order by sum(sales_amount) desc) rank_customer
from fact_sales f
left join customers c
on f.customer_key=c.customer_key
group by  f.customer_key,
concat(c.first_name,' ',c.last_name)
) as ranked_customer
where rank_customer<=10
order by rank_customer

